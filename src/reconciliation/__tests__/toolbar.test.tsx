import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { fixtureId, fixtureQueue, fixtureScene } from '../../../test-fixtures/reconciliation/scenes'
import { Overview } from '../../../test-fixtures/reconciliation/Overview'
import type { FloorScene } from '../presentation'
import { preferencesKey } from '../presentationPreferences'

const observed = vi.hoisted(() => ({ scene: null as unknown }))
vi.mock('../useFloorScene', () => ({ useFloorScene: () => ({ scene: observed.scene, error: null, now: Date.now() }) }))
vi.mock('../useDeskQueue', () => ({ useDeskQueue: () => ({ queue: fixtureQueue(), error: null }) }))
vi.mock('../../components/agentIcon', () => ({ AgentIcon: () => null }))
let scene: FloorScene
beforeEach(() => {
  localStorage.clear()
  scene = fixtureScene()
  const link = scene.claims.find(c => c.cardId === fixtureId(1))!
  scene.claims.push({ ...link, id: 'toolbar-fanout', cardId: fixtureId(6) })
  observed.scene = scene
  vi.stubGlobal('ResizeObserver', class { observe() {} disconnect() {} })
  Element.prototype.scrollIntoView = vi.fn()
})
afterEach(() => { cleanup(); localStorage.clear(); vi.unstubAllGlobals() })
const mount = () => render(<Overview workers={[]} messages={[]} submit={vi.fn()} />)
const slice = (name: string) => screen.getByRole('button', { name })
const cardIds = (host: HTMLElement) => [...host.querySelectorAll<HTMLElement>('.ov-card')].map(el => el.dataset.entityId).sort()

describe('Overview toolbar and filter shelf', () => {
  it('starts with friendly presets, collapsed Customize, labelled donuts and reachable clear', () => {
    const { container } = mount()
    expect(screen.queryByRole('heading', { name: 'Overview' })).toBeNull()
    expect(container.querySelector('.ov-top')).toBeNull()
    expect(container.querySelector('.ov-intro')).toBeNull()
    expect(screen.getByRole('button', { name: 'By Initiative' })).toHaveAttribute('aria-pressed', 'true')
    expect(screen.queryByLabelText('Outer grouping')).toBeNull()
    expect(screen.getByRole('button', { name: 'Clear all' })).toBeDisabled()
    expect(screen.getByRole('region', { name: 'Cards statuses' })).toHaveTextContent('5 / 5')
    expect(screen.getByRole('region', { name: 'Workers statuses' })).toHaveTextContent('5 / 5')

  })
  it('shows Custom scope chosen through Filters and opens those controls from its scope token', () => {
    scene.cards.find(card => card.id === fixtureId(1))!.source.properties.Status!.value = 'Done'
    const { container } = mount()
    fireEvent.click(screen.getByRole('button', { name: 'Customize' }))
    fireEvent.click(screen.getByRole('button', { name: 'Filters', exact: true }))
    for (const checkbox of screen.getAllByRole('checkbox')) {
      if ((checkbox as HTMLInputElement).checked) fireEvent.click(checkbox)
    }
    fireEvent.click(screen.getByRole('checkbox', { name: 'Done' }))
    expect(screen.getByLabelText('Status preset')).toHaveValue('custom')
    const shelf = screen.getByRole('complementary', { name: 'Applied filters' })
    expect(shelf).toHaveTextContent('Active filters 1')
    expect(within(shelf).queryByText('No active filters')).toBeNull()
    expect(cardIds(container)).toEqual([fixtureId(1)])
    fireEvent.click(screen.getByRole('button', { name: 'Close Customize' }))
    const scope = screen.getByRole('button', { name: 'Edit Status scope: Custom - Done' })
    fireEvent.click(scope)
    expect(screen.getByRole('region', { name: 'Filters', exact: true })).toBeTruthy()
    expect(screen.getByRole('checkbox', { name: 'Done' })).toBeChecked()
    expect(screen.getByLabelText('Status preset')).toHaveValue('custom')
    fireEvent.keyDown(screen.getByRole('checkbox', { name: 'Done' }), { key: 'Escape' })
    expect(scope).toHaveFocus()
    expect(screen.getByRole('button', { name: 'Clear all' })).toBeDisabled()
    expect(cardIds(container)).toEqual([fixtureId(1)])
  })
  it('offers Operational status only in Order and rejects grouping drops', () => {
    mount()
    fireEvent.click(screen.getByRole('button', { name: 'Customize' }))
    for (const label of ['Outer grouping', 'Inner grouping']) {
      const select = screen.getByLabelText(label)
      expect(within(select).queryByRole('option', { name: 'Operational status' })).toBeNull()
      const previous = (select as HTMLSelectElement).value
      fireEvent.drop(select.closest('label')!, { dataTransfer: { getData: () => 'operational' } })
      expect(select).toHaveValue(previous)
    }
    const order = screen.getByLabelText('Order by')
    fireEvent.change(order, { target: { value: 'priority' } })
    fireEvent.change(order, { target: { value: 'operational' } })
    expect(order).toHaveValue('operational')
    fireEvent.click(screen.getByRole('button', { name: 'Fields' }))
    expect(within(screen.getByRole('region', { name: 'Fields' })).queryByRole('button', { name: /Operational status/ })).toBeNull()
  })
  it('keeps every advanced control, custom edits and keyboard focus through Customize', () => {
    mount()
    const customize = screen.getByRole('button', { name: 'Customize' })
    fireEvent.click(customize)
    expect(screen.getByLabelText('Outer grouping')).toHaveValue('initiative')
    expect(screen.getByLabelText('Inner grouping')).toHaveValue('manager')
    expect(screen.getByLabelText('Order by')).toHaveValue('operational')
    fireEvent.change(screen.getByLabelText('Order by'), { target: { value: 'due' } })
    fireEvent.click(screen.getByRole('button', { name: 'Reverse sort direction' }))
    fireEvent.click(screen.getByRole('button', { name: 'Fields' }))
    expect(screen.getByRole('region', { name: 'Fields' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Filters' }))
    expect(screen.getByRole('button', { name: 'Links' })).toBeTruthy()
    expect(screen.getByRole('button', { name: /Gaps only/ })).toBeTruthy()
    expect(screen.getByRole('button', { name: 'Detailed' })).toBeTruthy()
    expect(screen.getByRole('button', { name: 'Reset' })).toBeTruthy()
    fireEvent.keyDown(screen.getByLabelText('Order by'), { key: 'Escape' })
    expect(customize).toHaveFocus()
    expect(screen.queryByLabelText('Order by')).toBeNull()
    fireEvent.click(customize)
    expect(screen.getByLabelText('Order by')).toHaveValue('due')
    expect(screen.getByRole('button', { name: 'Reverse sort direction' })).toHaveAttribute('title', 'Descending')
    fireEvent.click(screen.getByRole('button', { name: 'By Machine' }))
    expect(screen.getByLabelText('Outer grouping')).toHaveValue('machine')
    expect(screen.getByLabelText('Inner grouping')).toHaveValue('initiative')
    expect(screen.getByLabelText('Order by')).toHaveValue('operational')
  })
  it('toggles slices with mouse/keyboard, exposes text alternatives, and never reveals filtered counterparts on expansion', () => {
    const { container } = mount()
    const waiting = slice('Cards: Waiting For, 1')
    waiting.focus()
    fireEvent.keyDown(waiting, { key: ' ' })
    expect(slice('Cards: Waiting For, 1')).toHaveAttribute('aria-pressed', 'true')
    expect(cardIds(container)).toEqual([fixtureId(4)])
    expect(container.querySelectorAll('.ov-execution')).toHaveLength(5)
    fireEvent.keyDown(slice('Cards: In Progress, 4'), { key: 'Enter' })
    expect(cardIds(container)).toEqual([1, 2, 3, 4, 6].map(fixtureId).sort())
    fireEvent.click(slice('Workers: Running, 2'))
    expect(cardIds(container)).toEqual([fixtureId(1), fixtureId(6)])
    expect(container.querySelectorAll('.ov-execution')).toHaveLength(2)
    expect(container.textContent).not.toContain('No linked worker')
    fireEvent.click(container.querySelector('.ov-execution')!)
    expect(cardIds(container)).toEqual([fixtureId(1), fixtureId(6)])
    const menu = screen.getByRole('region', { name: 'Cards statuses' })
    expect(within(menu).getByRole('button', { name: /Waiting For.*0/ })).toHaveAttribute('aria-pressed', 'true')
    fireEvent.click(screen.getByRole('button', { name: 'Clear all' }))
    expect(cardIds(container)).toHaveLength(5)
    expect(container.querySelectorAll('.ov-execution')).toHaveLength(5)
  })
  it('preserves both selections on preset changes, reload and source status updates, then clears to the saved base scope', () => {
    localStorage.setItem(preferencesKey, JSON.stringify({ statusFilter: { preset: 'all', statuses: [] } }))
    const first = mount()
    fireEvent.click(slice('Cards: In Progress, 4'))
    fireEvent.click(slice('Workers: Running, 2'))
    fireEvent.click(screen.getByRole('button', { name: 'By Manager' }))
    first.unmount()
    const second = mount()
    expect(screen.getByRole('button', { name: 'By Manager' })).toHaveAttribute('aria-pressed', 'true')
    expect(slice('Cards: In Progress, 2')).toHaveAttribute('aria-pressed', 'true')
    expect(cardIds(second.container)).toEqual([fixtureId(1), fixtureId(6)])
    scene.cards.find(c => c.id === fixtureId(1))!.source.properties.Status!.value = 'Waiting For'
    second.rerender(<Overview workers={[]} messages={[]} submit={vi.fn()} />)
    expect(cardIds(second.container)).toEqual([fixtureId(6)])
    fireEvent.click(screen.getByRole('button', { name: 'Clear all' }))
    expect(cardIds(second.container)).toHaveLength(7)
    fireEvent.click(screen.getByRole('button', { name: 'Customize' }))
    expect(screen.getByLabelText('Status preset')).toHaveValue('all')
  })
  it('keeps zero-result selections removable without hiding opposite candidates', () => {
    localStorage.setItem(preferencesKey, JSON.stringify({ donutFilter: { cards: ['Waiting For'], workers: ['Running'] } }))
    const { container } = mount()
    expect(cardIds(container)).toEqual([])
    expect(container.querySelectorAll('.ov-execution')).toHaveLength(4)
    expect([...container.querySelectorAll('.ov-filter-chips button')].map(el => el.getAttribute('aria-label'))).toEqual(['Remove Workers: Running', 'Remove Cards: Waiting For'])
    expect(screen.getByText('Nothing is Waiting For right now')).toBeTruthy()
    expect(slice('Workers: Blocked, 1')).toHaveAttribute('aria-pressed', 'false')
    expect(slice('Cards: In Progress, 2')).toHaveAttribute('aria-pressed', 'false')
    fireEvent.click(screen.getByRole('button', { name: 'Remove Cards: Waiting For' }))
    expect(cardIds(container)).toEqual([fixtureId(1), fixtureId(6)])
    fireEvent.click(screen.getByRole('button', { name: 'Clear all' }))
    expect(cardIds(container)).toHaveLength(5)
  })
  it('labels unavailable source counts as unknown instead of asserting a verified zero', () => {
    scene.executions = []
    for (const home of scene.coverage.homes) home.observation.status = 'unknown'
    const { container } = mount()
    expect(screen.getByRole('region', { name: 'Workers statuses' })).toBeTruthy()
    expect(container.querySelector('.ov-headings')).toHaveTextContent('WORKERS · unavailable')
    expect(container.querySelector('.ov-headings')).not.toHaveTextContent('WORKERS · 0')
  })

})
